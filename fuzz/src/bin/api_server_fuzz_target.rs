#[cfg(feature = "afl_fuzz")]
#[macro_use]
extern crate afl;

use fuzzer::*;

#[cfg(feature = "afl_fuzz")]
afl_main!(fuzzing::target);

#[cfg(feature = "stdin_fuzz")]
stdin_main!(fuzzing::target);

pub mod fuzzing {
    extern crate libc;

    use std::io::Write;
    use std::os::unix::net::UnixStream;
    use std::sync::mpsc::{self, channel};

    use firecracker::api_server::ApiServer;
    use micro_http::HttpConnection;
    use vmm::builder::StartMicrovmError;
    use vmm::rpc_interface::{ApiRequest, ApiResponse, VmmActionError};
    use vmm_sys_util::eventfd::EventFd;

    // Wrapper over the api_server
    pub struct ApiServerFuzzer {
        api_server: ApiServer,
    }

    impl ApiServerFuzzer {
        fn new(
            api_request_sender: mpsc::Sender<ApiRequest>,
            vmm_response_receiver: mpsc::Receiver<ApiResponse>,
            to_vmm_fd: EventFd,
        ) -> ApiServerFuzzer {
            ApiServerFuzzer {
                api_server: ApiServer::new(api_request_sender, vmm_response_receiver, to_vmm_fd),
            }
        }
    }

    pub fn target(data: &[u8]) {
        // FD on which we notify the VMM that we have sent at least one `VmmRequest`.
        let to_vmm_fd = EventFd::new(libc::EFD_NONBLOCK).unwrap();

        // Creates a new asynchronous channel which allows passing messages to the VMM.
        let (api_request_sender, _from_api) = channel();
        // Receiver which collects messages from the VMM.
        let (to_api, vmm_response_receiver) = channel();

        // Create a new api_server instance
        let mut api_server =
            ApiServerFuzzer::new(api_request_sender, vmm_response_receiver, to_vmm_fd);

        // Attempts to send a value on this channel, returning it back if it could not be sent.
        to_api
            .send(Box::new(Err(VmmActionError::StartMicrovm(
                StartMicrovmError::MissingKernelConfig,
            ))))
            .unwrap();

        let (mut sender, receiver) = UnixStream::pair().unwrap();

        // Creates an empty connection.
        let mut connection = HttpConnection::new(receiver);

        // Send input generated by the fuzzer.
        sender.write_all(data).unwrap();
        if connection.try_read().is_ok() {
            // If we can read new bytes from the stream we try to get the first parsed request.
            let req = connection.pop_parsed_request();
            if req.is_some() {
                // If the request is not empty we try to handle it.
                let request_processing_start_us =
                    utils::time::get_time_us(utils::time::ClockType::Monotonic);
                let _response = api_server
                    .api_server
                    .handle_request(&req.unwrap(), request_processing_start_us);
            }
        }
    }
}
